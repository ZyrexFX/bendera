export const dictionaries = { id, en } as const;

export type Dictionary = typeof id;

export function getDictionary(lang: Lang): Dictionary {
  return dictionaries[lang] ?? dictionaries.id;
}

export function regionLabel(region: string, lang: Lang): string {
  const map = getDictionary(lang).regions;
  return map[region] ?? region;
}

export function subregionLabel(subregion: string, lang: Lang): string {
  if (!subregion) return subregion;
  const map = getDictionary(lang).subregions;
  return map[subregion] ?? subregion;
}

export function typeLabel(type: string, lang: Lang): string {
  if (!type) return type;
  const map = getDictionary(lang).types;
  return map[type] ?? type;
}

export function levelLabel(level: number, lang: Lang): string {
  const levels = getDictionary(lang).levels;
  return levels[level as 1 | 2 | 3 | 4]?.label ?? "";
}
